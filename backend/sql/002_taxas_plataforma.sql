-- Etapa não destrutiva. Executar antes de publicar a nova API.
-- Preserva integralmente saldos e históricos antigos para arquivo/auditoria.
begin;

create table if not exists public.configuracao_financeira (
  singleton boolean primary key default true check (singleton),
  percentual_taxa numeric(5,2) not null check (percentual_taxa between 0 and 100)
);
-- Único local de configuração da porcentagem. Alterações futuras só afetam novas taxas.
insert into public.configuracao_financeira(singleton, percentual_taxa)
values(true,5) on conflict(singleton) do nothing;

create table if not exists public.taxas_plataforma (
  id bigint generated by default as identity primary key,
  pedido_id bigint not null unique references public.pedidos(id_pedido),
  freelancer_id uuid not null references public.profiles(id),
  valor_servico numeric(12,2) not null check(valor_servico >= 0),
  percentual_taxa numeric(5,2) not null check(percentual_taxa between 0 and 100),
  valor_taxa numeric(12,2) not null check(valor_taxa >= 0),
  valor_liquido numeric(12,2) not null check(valor_liquido >= 0),
  status varchar(20) not null default 'pendente' check(status in ('pendente','paga','cancelada')),
  concluido_em timestamptz not null,
  criado_em timestamptz not null default now(),
  pago_em timestamptz,
  check(valor_taxa = round(valor_servico * percentual_taxa / 100,2)),
  check(valor_liquido = valor_servico - valor_taxa),
  check((status = 'paga') = (pago_em is not null))
);
create index if not exists idx_taxas_freelancer_data on public.taxas_plataforma(freelancer_id,concluido_em desc,id desc);

alter table public.configuracao_financeira enable row level security;
alter table public.taxas_plataforma enable row level security;
revoke all on public.configuracao_financeira,public.taxas_plataforma from anon,authenticated;
grant select on public.taxas_plataforma to authenticated;
drop policy if exists taxas_leitura_propria on public.taxas_plataforma;
create policy taxas_leitura_propria on public.taxas_plataforma for select to authenticated
using (freelancer_id = auth.uid() and exists(select 1 from public.profiles where id=auth.uid() and tipo_usuario='freelancer'));
grant all on public.configuracao_financeira,public.taxas_plataforma to service_role;
grant usage,select on sequence public.taxas_plataforma_id_seq to service_role;

-- Executado pelo servidor PostgreSQL na MESMA transação da conclusão do pedido.
-- Falha no registro da taxa desfaz a conclusão, sem estado financeiro parcial.
create or replace function public.tefreela_registrar_taxa()
returns trigger language plpgsql security definer set search_path = '' as $$
declare percentual numeric(5,2); taxa numeric(12,2);
begin
  if new.status <> 'concluido' then return new; end if;
  select percentual_taxa into strict percentual from public.configuracao_financeira where singleton;
  taxa := round(new.valor * percentual / 100,2);
  insert into public.taxas_plataforma(pedido_id,freelancer_id,valor_servico,percentual_taxa,valor_taxa,valor_liquido,concluido_em)
  values(new.id_pedido,new.id_freelancer,new.valor,percentual,taxa,new.valor-taxa,coalesce(new.data_entrega,now()))
  on conflict(pedido_id) do nothing;
  return new;
end $$;
revoke all on function public.tefreela_registrar_taxa() from public,anon,authenticated;
drop trigger if exists tefreela_taxa_ao_concluir on public.pedidos;
create trigger tefreela_taxa_ao_concluir after insert or update of status on public.pedidos
for each row execute function public.tefreela_registrar_taxa();

-- Também registra uma única taxa simulada para pedidos já concluídos.
insert into public.taxas_plataforma(pedido_id,freelancer_id,valor_servico,percentual_taxa,valor_taxa,valor_liquido,concluido_em)
select p.id_pedido,p.id_freelancer,p.valor,c.percentual_taxa,round(p.valor*c.percentual_taxa/100,2),
 p.valor-round(p.valor*c.percentual_taxa/100,2),coalesce(p.data_entrega,p.atualizado_em,p.criado_em,now())
from public.pedidos p cross join public.configuracao_financeira c where p.status='concluido' and c.singleton
on conflict(pedido_id) do nothing;

create or replace function public.tefreela_resumo_taxas(p_freelancer_id uuid)
returns jsonb language sql stable security definer set search_path = '' as $$
 select jsonb_build_object(
  'total_concluidos',count(*) filter(where status <> 'cancelada'),
  'valor_bruto',coalesce(sum(valor_servico) filter(where status <> 'cancelada'),0),
  'total_taxas',coalesce(sum(valor_taxa) filter(where status <> 'cancelada'),0),
  'valor_liquido',coalesce(sum(valor_liquido) filter(where status <> 'cancelada'),0),
  'taxas_pendentes',count(*) filter(where status = 'pendente'),
  'valor_pendente',coalesce(sum(valor_taxa) filter(where status = 'pendente'),0),
  'percentual_atual',(select percentual_taxa from public.configuracao_financeira where singleton),
  'simulado',true)
 from public.taxas_plataforma where freelancer_id=p_freelancer_id;
$$;

create or replace function public.tefreela_simular_taxa(p_taxa_id bigint,p_freelancer_id uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare taxa public.taxas_plataforma%rowtype;
begin
 if not exists(select 1 from public.profiles where id=p_freelancer_id and tipo_usuario='freelancer') then
  raise exception 'Ação exclusiva de freelancers' using errcode='42501';
 end if;
 select * into taxa from public.taxas_plataforma where id=p_taxa_id and freelancer_id=p_freelancer_id for update;
 if not found then raise exception 'Taxa não encontrada' using errcode='P0002'; end if;
 if taxa.status='cancelada' or not exists(select 1 from public.pedidos where id_pedido=taxa.pedido_id and status='concluido' and id_freelancer=p_freelancer_id) then
  raise exception 'Taxa não pode ser simulada' using errcode='P0001';
 end if;
 if taxa.status='paga' then return to_jsonb(taxa); end if;
 update public.taxas_plataforma set status='paga',pago_em=now() where id=taxa.id returning * into taxa;
 return to_jsonb(taxa);
end $$;
revoke all on function public.tefreela_resumo_taxas(uuid),public.tefreela_simular_taxa(bigint,uuid) from public,anon,authenticated;
grant execute on function public.tefreela_resumo_taxas(uuid),public.tefreela_simular_taxa(bigint,uuid) to service_role;

